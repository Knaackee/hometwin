import assert from 'node:assert/strict';
import { validArea, mapTransform, cleaningZone } from '../frontend/src/robot-geometry.js';
const points=[[0,0],[2,0],[2,3],[0,3]], area={scope:'ground',kind:'work',points};
const pairs=[{home:[0,0],robot:[20000,20000]},{home:[5,0],robot:[25000,20000]},{home:[0,5],robot:[20000,25000]}];
const profile={scope:'ground',entity_id:'vacuum.test',map_name:'Ground',pairs};
assert.deepEqual(cleaningZone(area,profile,[]),[20000,20000,22000,23000]);
assert.deepEqual(mapTransform(pairs)([1,2]),[21000,22000]);
const mirrored=pairs.map(p=>({...p,robot:[40000-p.robot[0],p.robot[1]]}));
assert.deepEqual(cleaningZone(area,{...profile,pairs:mirrored},[]),[18000,20000,20000,23000]);
const rotated=pairs.map(p=>({...p,robot:[p.robot[1],p.robot[0]]}));
assert.deepEqual(cleaningZone(area,{...profile,pairs:rotated},[]),[20000,20000,23000,22000]);
for(const bad of [[],[[0,0],[1,1],[0,1],[1,0]],[[0,0],[0,0],[1,1]],[[NaN,0],[1,0],[0,1]]])assert(!validArea(bad));
assert(validArea([[0,0],[2,2]],true));
for(const bad of [[],pairs.map(p=>({...p,home:[0,0]})),pairs.map(p=>({...p,robot:p.home})),pairs.map(p=>({...p,home:[null,0]}))])assert.throws(()=>mapTransform(bad),/calibration/);
assert.throws(()=>cleaningZone({...area,scope:'site'},profile,[]),/zone/);
assert.throws(()=>cleaningZone(area,{...profile,map_name:''},[]),/mapName/);
assert.throws(()=>cleaningZone({...area,points:[[0,0],[2,0],[1,3]]},profile,[]),/rectangle/);
assert.throws(()=>cleaningZone(area,profile,[{scope:'ground',kind:'exclude',points:[[.5,.5],[1,.5],[1,1],[.5,1]]}]),/excluded/);
assert.throws(()=>cleaningZone(area,profile,[{scope:'ground',kind:'line',points:[[-1,1],[4,1]]}]),/excluded/);
assert.deepEqual(cleaningZone(area,profile,[{scope:'other',kind:'line',points:[[-1,1],[4,1]]}]),[20000,20000,22000,23000]);
console.log('PASS: calibration, reflection, axis rotation, polygon validation, exclusions, scope and exact rectangle guards');
