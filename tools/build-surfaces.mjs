import assert from 'node:assert/strict';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeSurfaceDefinition } from '../engine/surface.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = resolve(root, 'surfaces');
const output = resolve(root, 'frontend/src/surfaces.gen.js');
const files = readdirSync(sourceDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, 'en'));

assert(files.length, 'No surface definitions found');
const seen = new Set();
const definitions = files.map((file) => {
  let parsed;
  try { parsed = JSON.parse(readFileSync(resolve(sourceDir, file), 'utf8')); }
  catch (error) { throw new Error(`${file}: invalid JSON (${error.message})`); }
  let normalized;
  try { normalized = normalizeSurfaceDefinition(parsed); }
  catch (error) { throw new Error(`${file}: ${error.message}`); }
  assert(!seen.has(normalized.id), `${file}: duplicate surface id "${normalized.id}"`);
  assert.equal(file, `${normalized.id}.json`, `${file}: filename must match surface id "${normalized.id}"`);
  seen.add(normalized.id);
  return normalized;
});

const imports = files.map((file, index) => `import surface${index} from '../../surfaces/${file}' with { type: 'json' };`).join('\n');
const generated = `// generated by tools/build-surfaces.mjs from surfaces/ - do not edit\n${imports}\n\nexport const BUNDLED_SURFACES = [${definitions.map((_, index) => `surface${index}`).join(', ')}];\n`;

if (process.argv.includes('--check')) {
  assert.equal(readFileSync(output, 'utf8'), generated, `${relative(root, output)} is stale; run node tools/build-surfaces.mjs`);
  console.log(`${definitions.length} surface definitions valid`);
} else {
  writeFileSync(output, generated);
  console.log(`bundled ${definitions.length} surface definitions`);
}
